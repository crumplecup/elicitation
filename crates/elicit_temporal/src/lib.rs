//! `elicit_temporal` — Temporal contract interface crate.
//!
//! Provides a standards-anchored vocabulary of temporal propositions (`contracts`)
//! for date, time, offset, and timestamp interchange across producer and
//! consumer crates, plus neutral descriptors (`types`) and object-safe runtime
//! seams (`traits`) that exchange `Established<P>` proof sidecars.
//!
//! # Design
//!
//! This crate is an interface layer, not an implementation. Temporal producers
//! such as `elicit_time`, `elicit_chrono`, and `elicit_jiff` can establish these
//! propositions; downstream consumers can require them without coupling to a
//! particular datetime backend.
//!
//! The current implementation remains contract-first, but now includes an
//! initial runtime seam: neutral temporal descriptors, a crate-local
//! `TemporalError`/`TemporalResult`, and object-safe parser, formatter, zone,
//! conversion, interval, and reporter trait families.

